import math

board = ['' for _ in range(9)]

def print_board():
    for i in range(3):
        print(board[3*i], '|', board[3*i+1], '|', board[3*i+2])
        if i < 2:
           print('---------')

def is_winner(b, player):

     wins = [
      (0,1,2), (3,4,5), (6,7,8),
      (0,3,6), (1,4,7), (2,5,8),
      (0,4,8), (2,4,6)
     ]
     for a,b_,c in wins:
        if b[a] == b[b_] == b[c] == player:
            return True
     return False

def is_board_full(b):
  return '' not in b

def minimax(b, depth, is_maximizing):

  if is_winner(b, 'X'):
    return 10 - depth
  if is_winner(b, '0'):
    return depth - 10
  if is_board_full(b):
    return 0

  if is_maximizing:
    best_score = -math.inf
    for i in range(9):
      if b[i] == '':
        b[i] = 'X'
        score = minimax(b, depth + 1, False)
        b[i] = ''
        best_score = max(score, best_score)
    return best_score
  else:
    best_score = math.inf
    for i in range(9):
      if b[i] == '':
        b[i] = '0'
        score = minimax(b, depth + 1, True)
        b[i] = ''
        best_score = min(score, best_score)
    return best_score

def best_move():

  best_score = -math.inf
  move = -1
  for i in range(9):
    if board[i] == '':
      board[i] = 'X'
      score = minimax(board, 0, False)
      board[i] = ''
      if score > best_score:
        best_score = score
        move = i
  return move

def play_game():

  print("Board positions are numbered 0 to 8:")
  print("0 | 1 | 2")
  print('---------')
  print("3 | 4 | 5")
  print('---------')
  print("6 | 7 | 8")
  print()

  while True:

    move = best_move()
    if move == -1:
      print("Game over! It's a tie.")
      break
    board[move] = 'X'
    print("AI (X) plays move:", move)
    print_board()
    if is_winner(board, 'X'):
        print("AI (X) wins!")
        break
    if is_board_full(board):
        print("Game over! It's a tie.")
        break

    while True:
       try:
          human_move = int(input("Enter your move (0-8): "))
          if 0 <= human_move <= 8 and board[human_move] == '':
            board[human_move] = '0'
            break
          else:
               print("Inavalid move. Try again.")
       except ValueError:
        print("Please enter a valid number.")

    print_board()
    if is_winner(board, '0'):
        print("You win!")
        break
    if is_board_full(board):
        print("Game over! It's a tie.")
        break

